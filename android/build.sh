#!/bin/bash
# Builds Thurea for Android (no Gradle): Rust core for every ABI → aapt2 → javac → d8 →
# native libs into the APK → zipalign → apksigner.
#
# Signed with Thurea's Android release key (~/.config/thurea/android-release.jks): every update
# must use the same key to install over the device owner. Override with THUREA_KEYSTORE /
# THUREA_KEYSTORE_PASS.
set -euo pipefail
A=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd "$A/.." && pwd)
SDK=~/Android/Sdk; BT=$SDK/build-tools/35.0.0; JAR=$SDK/platforms/android-35/android.jar
NDK=${ANDROID_NDK_HOME:-$(ls -d "$SDK"/ndk/* | sort -V | tail -1)}
LLVM=$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin
export JAVA_HOME=/usr/lib/jvm/java-17-openjdk PATH=/usr/lib/jvm/java-17-openjdk/bin:$HOME/.cargo/bin:$PATH
B=$A/build; rm -rf "$B"; mkdir -p "$B/res" "$B/gen" "$B/classes" "$B/dex" "$B/apk"

# 0. Verse of the day from the shared list (policy/verses.json: World English Bible, public domain).
python3 -I - "$ROOT/policy/verses.json" "$A/src/com/thurea/guard/Verses.java" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
q = lambda s: json.dumps(s, ensure_ascii=False)
rows = ",\n".join(f"        {{{q(v['ref'])}, {q(v['text'])}}}" for v in d["verses"])
open(sys.argv[2], "w").write(f"""package com.thurea.guard;

import java.time.LocalDate;

/** Verse of the day, the same list and order as Thurea on Windows and Linux. Generated by build.sh from policy/verses.json. */
final class Verses {{
    static final String TRANSLATION = {q(d["abbreviation"])};
    static final String NOTICE = {q(d["notice"])};

    private static final String[][] V = {{
{rows}
    }};

    /** {{reference, text}} for today (one per day, in order; day 0 = 1970-01-01). */
    static String[] today() {{
        return V[(int) Math.floorMod(LocalDate.now().toEpochDay(), (long) V.length)];
    }}

    /** Shown unless switched off in Settings. */
    static boolean on(android.content.Context c) {{
        return c.getSharedPreferences("prefs", android.content.Context.MODE_PRIVATE).getBoolean("verses", true);
    }}

    private Verses() {{}}
}}
""")
PY

# 1. Rust core (crates/thurea-android), 16 KB page aligned for Android 15+.
export CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER=$LLVM/aarch64-linux-android29-clang
export CARGO_TARGET_ARMV7_LINUX_ANDROIDEABI_LINKER=$LLVM/armv7a-linux-androideabi29-clang
export CARGO_TARGET_X86_64_LINUX_ANDROID_LINKER=$LLVM/x86_64-linux-android29-clang
export RUSTFLAGS="-C link-arg=-Wl,-z,max-page-size=16384"
(cd "$ROOT" && cargo build --release -p thurea-android \
  --target aarch64-linux-android --target armv7-linux-androideabi --target x86_64-linux-android)
for pair in aarch64-linux-android:arm64-v8a armv7-linux-androideabi:armeabi-v7a x86_64-linux-android:x86_64; do
  mkdir -p "$B/apk/lib/${pair#*:}"
  cp "$ROOT/target/${pair%%:*}/release/libthurea_android.so" "$B/apk/lib/${pair#*:}/"
done

# 2. Java layer.
"$BT/aapt2" compile --dir "$A/res" -o "$B/res/res.zip"
"$BT/aapt2" link -o "$B/unsigned.apk" -I "$JAR" --min-sdk-version 29 --target-sdk-version 35 --manifest "$A/AndroidManifest.xml" --java "$B/gen" "$B/res/res.zip"
javac -source 17 -target 17 -Xlint:-options -classpath "$JAR" -d "$B/classes" $(find "$A/src" "$B/gen" -name '*.java')
"$BT/d8" --release --min-api 29 --lib "$JAR" --output "$B/dex" $(find "$B/classes" -name '*.class')
(cd "$B/dex" && zip -qj "$B/unsigned.apk" classes.dex)
(cd "$B/apk" && zip -qr0 "$B/unsigned.apk" lib)
"$BT/zipalign" -f -P 16 4 "$B/unsigned.apk" "$B/aligned.apk"

# 3. Sign with Thurea's release key (every update must use the same key).
KS=${THUREA_KEYSTORE:-$HOME/.config/thurea/android-release.jks}
PW=${THUREA_KEYSTORE_PASS:-$HOME/.config/thurea/android-keystore-pass}
[ -f "$KS" ] && [ -f "$PW" ] || { echo "Release key not found ($KS). Set THUREA_KEYSTORE and THUREA_KEYSTORE_PASS."; exit 1; }
"$BT/apksigner" sign --ks "$KS" --ks-pass "file:$PW" --ks-key-alias thurea --out "$A/Thurea.apk" "$B/aligned.apk"
"$BT/apksigner" verify "$A/Thurea.apk" && ls -la "$A/Thurea.apk"
